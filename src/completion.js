/**
 * Static shell completion scripts generated from the command table.
 * They only need the group/action names, so no runtime completion engine is
 * required on the user's machine.
 */

export function completionScript(table, shell) {
  const groups = table.groups;
  const byGroup = new Map();
  for (const cmd of table.commands) {
    if (!byGroup.has(cmd.group)) byGroup.set(cmd.group, new Set());
    const node = byGroup.get(cmd.group);
    for (const token of cmd.tokens) node.add(token);
  }
  const actionsFor = (group) => [...(byGroup.get(group) ?? [])].sort();

  if (shell === 'bash') return bash(table, groups, actionsFor);
  if (shell === 'zsh') return zsh(table, groups, actionsFor);
  return fish(table, groups, actionsFor);
}

const GLOBAL_FLAGS = [
  '--base-url', '--token', '--cookie', '--output', '--timeout', '--data', '--data-file',
  '--stdin', '--file', '--form', '--public', '--dry-run', '--verbose', '--quiet',
  '--no-color', '--help', '--version', '--out-file',
];

function bash(table, groups, actionsFor) {
  const groupsLiteral = groups.join(' ');
  const actionsLiteral = JSON.stringify(Object.fromEntries(groups.map((g) => [g, actionsFor(g)])));
  return `#!/usr/bin/env bash
# dockhand shell completion — generated by \`dockhand completion bash\`
_dockhand() {
  local cur prev words
  cur="\${COMP_WORDS[COMP_CWORD]}"
  prev="\${COMP_WORDS[COMP_CWORD-1]}"
  local groups="__GROUPS__"
  local actions='${actionsLiteral}'

  local i group=""
  for (( i=1; i < COMP_CWORD; i++ )); do
    case "\${COMP_WORDS[i]}" in
      -*) continue ;;
      *) group="\${COMP_WORDS[i]}"; break ;;
    esac
  done

  if [[ "\${cur}" == -* ]]; then
    COMPREPLY=( $(compgen -W "${GLOBAL_FLAGS.join(' ')}" -- "\${cur}") )
    return 0
  fi
  if [[ -z "\${group}" ]]; then
    COMPREPLY=( $(compgen -W "\${groups} login logout config completion raw help version" -- "\${cur}") )
    return 0
  fi
  local list="\${actions[\${group}]}"
  COMPREPLY=( $(compgen -W "\${list}" -- "\${cur}") )
  return 0
}
complete -F _dockhand dockhand
`.replace('__GROUPS__', groupsLiteral);
}

function zsh(table, groups, actionsFor) {
  const lines = [
    '#compdef dockhand',
    '# dockhand shell completion — generated by `dockhand completion zsh`',
    '_dockhand() {',
    '  local -a groups actions',
    `  groups=(${groups.map((g) => `'${g}'`).join(' ')})`,
    '  actions=(',
  ];
  for (const group of groups) {
    lines.push(`    '${group}:${actionsFor(group).join(' ')}'`);
  }
  lines.push('  )');
  lines.push(`  local -a globals`);
  lines.push(`  globals=(${GLOBAL_FLAGS.map((f) => `'${f}'`).join(' ')})`);
  lines.push('');
  lines.push('  if [[ ${words[CURRENT]} == -* ]]; then');
  lines.push('    compadd -- ${globals[@]}');
  lines.push('    return');
  lines.push('  fi');
  lines.push('');
  lines.push('  local i group=""');
  lines.push('  for (( i = 2; i < CURRENT; i++ )); do');
  lines.push('    case ${words[i]} in');
  lines.push('      -*) continue ;;');
  lines.push('      *) group=${words[i]}; break ;;');
  lines.push('    esac');
  lines.push('  done');
  lines.push('');
  lines.push('  if [[ -z ${group} ]]; then');
  lines.push('    compadd -- ${groups[@]} login logout config completion raw help version');
  lines.push('    return');
  lines.push('  fi');
  lines.push('');
  lines.push('  local entry');
  lines.push('  for entry in ${actions[@]}; do');
  lines.push('    if [[ ${entry%%:*} == ${group} ]]; then');
  lines.push('      compadd -- ${=entry#*:}');
  lines.push('      return');
  lines.push('    fi');
  lines.push('  done');
  lines.push('}');
  lines.push('');
  lines.push('_dockhand "$@"');
  return `${lines.join('\n')}\n`;
}

function fish(table, groups, actionsFor) {
  const lines = [
    '# dockhand shell completion — generated by `dockhand completion fish`',
    'complete -c dockhand -f',
  ];
  for (const group of groups) {
    lines.push(`complete -c dockhand -n "__fish_use_subcommand" -a ${group} -d "${describe(table, group)}"`);
    for (const action of actionsFor(group)) {
      const name = action === group ? 'help' : `${group} ${action}`;
      lines.push(`complete -c dockhand -n "__fish_seen_subcommand_from ${group}" -a "${action}" -d "${escape(descend(table, name))}"`);
    }
  }
  for (const flag of GLOBAL_FLAGS) {
    lines.push(`complete -c dockhand -l ${flag.replace(/^--/, '')}`);
  }
  return `${lines.join('\n')}\n`;
}

function describe(table, group) {
  const member = table.commands.find((c) => c.group === group);
  return escape(member?.summary ?? group);
}

function descend(table, name) {
  const cmd = table.commands.find((c) => c.name === name || c.aliases?.includes(name));
  return escape(cmd?.summary ?? name);
}

const escape = (text) => String(text).replace(/'/g, '').replace(/\s+/g, ' ').slice(0, 100);